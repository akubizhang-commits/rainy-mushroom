// SYNC-02（04 §2.4-1、§4.7，03 §2.1 / §13，09 A3）：js/survivor 与 cocos-pilot/assets/scripts/shared 副本
// 按 scripts/cocos/sync-shared.mjs 的 sha256 清单一致。只读，不运行同步脚本（`npm run cocos:sync` 负责写）。
import test from 'node:test'
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const manifest = JSON.parse(readFileSync(join(root, 'cocos-pilot/shared-manifest.json'), 'utf8'))
const sharedDir = join(root, 'cocos-pilot/assets/scripts/shared')
const HEADER = '// @ts-nocheck\n// GENERATED by scripts/cocos/sync-shared.mjs; edit the root JS source.\n'
// 不进清单的模块：只允许下列精确条目（BUG-S1-05：T2 遗留的版本占位，无任何引用，sync 依赖遍历不收集）。
const NOT_SHIPPED = ['js/survivor/index.js']

function walk(dir, ext, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) walk(p, ext, out)
    else if (name.endsWith(ext)) out.push(relative(root, p).split('\\').join('/'))
  }
  return out
}
const sources = walk(join(root, 'js/survivor'), '.js').sort()
const sha = (text) => createHash('sha256').update(text).digest('hex')

test('SYNC-02 清单覆盖全部 js/survivor 模块（除已登记的占位），且只含 js/survivor', () => {
  const listed = manifest.map((m) => m.source).sort()
  assert.equal(new Set(listed).size, listed.length, '清单无重复')
  assert.ok(listed.every((s) => s.startsWith('js/survivor/')), '清单只含 js/survivor')
  assert.deepEqual(listed, sources.filter((s) => !NOT_SHIPPED.includes(s)), '每个 js/survivor 模块都进清单')
  for (const s of NOT_SHIPPED) assert.ok(sources.includes(s), `登记的例外 ${s} 仍存在（删除后请同步移除此条）`)
})

test('SYNC-02 清单 sha256 = 当前源码；shared 副本 = 头注释 + 去 .js 后缀的源码', () => {
  for (const { source, sha256 } of manifest) {
    const original = readFileSync(join(root, source), 'utf8')
    assert.equal(sha256, sha(original), `${source} 源码与清单不一致，需 npm run cocos:sync`)
    const copy = join(sharedDir, source.replace(/\.js$/, '.ts'))
    assert.ok(existsSync(copy), `缺少副本 ${relative(root, copy)}`)
    const expected = HEADER + original.replace(/(from\s*['"][^'"]+)\.js(['"])/g, '$1$2')
    assert.equal(readFileSync(copy, 'utf8'), expected, `${source} 副本过期`)
  }
})

test('SYNC-02 shared 目录没有清单外的 survivor 副本；SurvivorBot / 测试夹具不进清单', () => {
  const copies = walk(join(sharedDir, 'js/survivor'), '.ts').map((p) => relative(relative(root, sharedDir), p).split('\\').join('/'))
  const expected = manifest.map((m) => m.source.replace(/\.js$/, '.ts')).sort()
  assert.deepEqual(copies.map((p) => p.replace(/^.*?js\/survivor\//, 'js/survivor/')).sort(), expected)
  assert.ok(!manifest.some((m) => /SurvivorBot|bot\.mjs|fixtures/i.test(m.source)), 'SurvivorBot / 夹具不在清单')
})
