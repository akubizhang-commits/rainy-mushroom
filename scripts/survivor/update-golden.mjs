// 重新生成 L2 回放金标准（04 §2.2-4）。不进构建、不被 sync。用法：
//   node scripts/survivor/update-golden.mjs            只按现有输入脚本重算 tests/fixtures/survivor/golden.json
//   node scripts/survivor/update-golden.mjs --inputs   先用 bot.mjs 重新固化 inputs-kite / inputs-win，再重算金标准
// 规则或数值有意变更时才运行；提交说明写明原因并引用 01 的对应改动（09 S3-D5）。
// --inputs 只在 R3 固化输入因规则变化不再通关时使用：固化后的输入不随 bot.mjs 后续改动变化。
// 同一代码下重复运行输出字节一致。
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { SurvivorRun } from '../../js/survivor/SurvivorRun.js'
import { steer, makePicker } from './bot.mjs'

const root = resolve(import.meta.dirname, '../..')
const dir = resolve(root, 'tests/fixtures/survivor')
const args = process.argv.slice(2)
for (const a of args) if (a !== '--inputs') throw new Error(`unknown argument: ${a}`)

const MAX_STEPS = 10 * 60 * 60 // 10 分钟
const HOLD = 6                  // 每 6 步（0.1 秒）重新取一次方向
const KITE_R = 200              // 绕圈半径
const KITE_W = 0.3              // 圆周切线权重
const r3 = (v) => Math.round(v * 1000) / 1000

// 跑一局并记录实际施加的输入（分段表）与每次升级的选卡下标。
function record(seed, policy, pick) {
  const run = new SurvivorRun({ seed, viewport: { width: 720, height: 1560 } })
  const picker = makePicker(pick, seed)
  const moves = []
  const picks = []
  let steps = 0
  let cur = null
  while (run.state !== 'won' && run.state !== 'lost' && steps < MAX_STEPS) {
    if (run.state === 'levelup') {
      const i = picker(run.offer)
      picks.push(i)
      run.choose(i)
      continue
    }
    if (steps % HOLD === 0) {
      const [x, y] = policy(run, steps)
      const v = [r3(x), r3(y)]
      if (!cur || cur[0] !== v[0] || cur[1] !== v[1]) { cur = v; moves.push([steps, v[0], v[1]]) }
    }
    run.setInput(cur[0], cur[1])
    run.step()
    steps += 1
    run.drainEvents()
  }
  return { seed, maxSteps: MAX_STEPS, moves, picks, defaultPick: 0 }
}

function writeInputs(file, name, header, script) {
  const rows = []
  for (let i = 0; i < script.moves.length; i += 8) rows.push('    ' + script.moves.slice(i, i + 8).map((m) => JSON.stringify(m)).join(', ') + ',')
  const text = `${header.map((l) => `// ${l}`).join('\n')}
// GENERATED by scripts/survivor/update-golden.mjs --inputs；不要手改。
export default Object.freeze({
  name: '${name}',
  seed: '${script.seed}',
  maxSteps: ${script.maxSteps},
  moves: Object.freeze([
${rows.join('\n')}
  ]),
  picks: Object.freeze(${JSON.stringify(script.picks)}),
  defaultPick: ${script.defaultPick},
})
`
  writeFileSync(resolve(dir, file), text)
  console.log(`wrote ${file}: ${script.moves.length} segments, ${script.picks.length} picks`)
}

if (args.includes('--inputs')) {
  const kite = (run, steps) => {
    const [fx, fy] = steer(run, 'flee')
    const a = (160 / KITE_R) * (steps / 60) + Math.PI / 2
    const x = fx + KITE_W * Math.cos(a)
    const y = fy + KITE_W * Math.sin(a)
    const m = Math.hypot(x, y) || 1
    return [x / m, y / m]
  }
  writeInputs('inputs-kite.mjs', 'kite', [
    'R2/R4/R5 绕圈（04 §2.2）：bot.mjs 保守逃跑型（flee）的斥力方向 + 0.3 × 半径 200 圆周切线',
    '（ω = 160 / 200 rad/s），每 6 步取一次方向、分量保留 3 位小数；选卡为 bot random（种子 replay-kite）。',
    '纯圆周开环输入约 2:30 就被包围圈笼罩，到不了 R2 要求的 300 秒哈希点，所以叠加 flee 斥力。',
  ], record('replay-kite', kite, 'random'))
  writeInputs('inputs-win.mjs', 'win', [
    'R3 完整通关（04 §2.2）：bot.mjs 贴孢子型（spore）+ prefer:spore_shot 在种子 replay-win-3 上的通关局，',
    'S3 B1–B4 后原种子 replay-win 在 10:24 才通关（超出 R3 的 [420, 600]），改用 replay-win-3；',
    '每 6 步取一次方向、分量保留 3 位小数后固化。',
  ], record('replay-win-3', (run) => steer(run, 'spore'), 'prefer:spore_shot'))
}

// 金标准：按输入脚本回放（与 tests/survivor-replay.test.mjs 同一驱动）。
const { replay } = await import('../../tests/fixtures/survivor/replay.mjs')
// 输入文件在本进程里先写后读（首次 import），不存在模块缓存问题。
const load = async (name) => (await import(`../../tests/fixtures/survivor/inputs-${name}.mjs`)).default
const KITE_HASH_STEPS = [60 * 60, 180 * 60, 300 * 60]
const golden = {}
for (const name of ['idle', 'kite', 'win']) {
  const script = await load(name)
  const r = replay(script, { hashAt: new Set(name === 'kite' ? KITE_HASH_STEPS : []) })
  golden[name] = { seed: script.seed, steps: r.steps, levelUps: r.levelUps, summary: r.summary }
  if (name === 'kite') golden[name].hashes = r.hashes
  console.log(`${name}: ${r.summary.outcome} at ${r.summary.survivalSec.toFixed(1)}s, Lv${r.summary.level}, ${r.steps} steps`)
}
writeFileSync(resolve(dir, 'golden.json'), JSON.stringify(golden, null, 2) + '\n')
console.log('wrote golden.json')
