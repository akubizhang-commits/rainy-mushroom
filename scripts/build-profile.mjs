import {readFileSync,writeFileSync,mkdirSync} from 'node:fs'
import {join} from 'node:path'

const runtimePath='cocos-pilot/assets/scripts/TowerBuildCapabilities.ts'
const profiles=Object.freeze(['production','qa'])
export function buildCapabilities(profile='production'){
 if(!profiles.includes(profile))throw Error('Unsupported build profile: '+profile)
 return Object.freeze({profile,developerTools:profile==='qa'})
}
export function profileFromArgs(args){
 let profile='production',seen=false
 for(let i=0;i<args.length;i++){
  const arg=args[i]
  if(!arg.startsWith('--profile'))continue
  if(seen)throw Error('Duplicate build profile flag')
  if(arg==='--profile')profile=args[++i]
  else if(arg.startsWith('--profile='))profile=arg.slice('--profile='.length)
  else throw Error('Invalid build profile flag: '+arg)
  seen=true
 }
 // An omitted value is invalid, while an omitted flag keeps production.
 if(seen&&profile===undefined)throw Error('Missing build profile value')
 buildCapabilities(profile)
 return profile
}
export function capabilitiesSource(profile){
 return '// GENERATED by scripts/prepare-release-config.mjs; select capabilities at build time only.\nexport const BUILD_CAPABILITIES=Object.freeze('+JSON.stringify(buildCapabilities(profile))+' as const);\n'
}
export function writeBuildCapabilities(root,profile='production'){
 const source=capabilitiesSource(profile),folder=join(root,'cocos-pilot/assets/scripts')
 mkdirSync(folder,{recursive:true})
 writeFileSync(join(root,runtimePath),source)
 writeFileSync(join(root,runtimePath+'.meta'),JSON.stringify({ver:'4.0.24',importer:'typescript',imported:true,uuid:'106a2f95-820d-4cfe-b2ee-f7b817533fd6',files:[],subMetas:{},userData:{}},null,2)+'\n')
}
export function readBuildProfile(root){
 const source=readFileSync(join(root,runtimePath),'utf8')
 const profile=profiles.find(value=>source===capabilitiesSource(value))
 if(!profile)throw Error('Invalid generated build capabilities; run prepare-release-config with an explicit profile')
 return profile
}
