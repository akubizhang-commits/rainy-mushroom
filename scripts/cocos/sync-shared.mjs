import {readFileSync,writeFileSync,mkdirSync,copyFileSync,existsSync,rmSync} from 'node:fs'
import {resolve,dirname,relative} from 'node:path'
import {createHash,randomUUID} from 'node:crypto'
import {EXPLORATION_SPECIES} from '../../js/data/explorationData.js'
const root=resolve(import.meta.dirname,'../..'),out=resolve(root,'cocos-pilot/assets/scripts/shared'),seen=new Set(),manifest=[]
function visit(file){
 if(seen.has(file))return
 if(!file.startsWith(root+'/js/'))throw Error('Unexpected shared dependency '+file)
 seen.add(file)
 const original=readFileSync(file,'utf8')
 for(const match of original.matchAll(/(?:from\s*|import\s*)['"]([^'"]+)['"]/g)){
  if(!match[1].startsWith('.'))throw Error('Shared dependency must be platform independent: '+match[1])
  visit(resolve(dirname(file),match[1]))
 }
 const rel=relative(root,file),target=resolve(out,rel.replace(/\.js$/,'.ts'))
 const converted='// @ts-nocheck\n// GENERATED by scripts/cocos/sync-shared.mjs; edit the root JS source.\n'+original.replace(/(from\s*['"][^'"]+)\.js(['"])/g,'$1$2')
 mkdirSync(dirname(target),{recursive:true});writeFileSync(target,converted)
 manifest.push({source:rel,sha256:createHash('sha256').update(original).digest('hex')})
}
visit(resolve(root,'js/cocos/GameSession.js'))
const photoBundles={}
for(const [speciesIndex,species] of EXPLORATION_SPECIES.entries()){
 const bundle=`catalogue-${speciesIndex%6}`;photoBundles[species.id]=bundle
 const folder=resolve(root,'cocos-pilot/assets',bundle);mkdirSync(folder,{recursive:true})
 const metaPath=folder+'.meta',meta=existsSync(metaPath)?JSON.parse(readFileSync(metaPath,'utf8')):{ver:'1.2.0',importer:'directory',imported:true,uuid:randomUUID(),files:[],subMetas:{}}
 meta.userData={isBundle:true,bundleName:bundle,priority:9,bundleConfigID:'default'};writeFileSync(metaPath,JSON.stringify(meta,null,2))
 for(const [i,file]of species.photos.entries())copyFileSync(resolve(root,file),resolve(folder,`${species.id}-${i}.jpg`))
}
// Only this generated directory is retired; the original photo assets are retained.
const oldPhotos=resolve(root,'cocos-pilot/assets/resources/photos');if(existsSync(oldPhotos))rmSync(oldPhotos,{recursive:true});if(existsSync(oldPhotos+'.meta'))rmSync(oldPhotos+'.meta')
writeFileSync(resolve(root,'cocos-pilot/assets/scripts/PhotoBundles.ts'),'// GENERATED by sync-shared.mjs\nexport const PHOTO_BUNDLES:Record<string,string>='+JSON.stringify(photoBundles,null,2)+';\n')
writeFileSync(resolve(root,'cocos-pilot/shared-manifest.json'),JSON.stringify(manifest,null,2)+'\n')
console.log(`Synced ${seen.size} modules and ${EXPLORATION_SPECIES.length*2} licensed existing photos`)
