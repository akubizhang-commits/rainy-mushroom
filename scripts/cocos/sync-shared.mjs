import {readFileSync,writeFileSync,mkdirSync,rmSync,existsSync,readdirSync} from 'node:fs';
import {resolve,dirname,relative} from 'node:path';
import {createHash} from 'node:crypto';
const root=resolve(import.meta.dirname,'../..'),out=resolve(root,'cocos-pilot/assets/scripts/shared'),seen=new Set(),manifest=[];
function visit(file){
 if(seen.has(file))return;
 if(!file.startsWith(root+'/js/xianxia/'))throw Error('Unexpected gameplay dependency: '+file);
 seen.add(file);const original=readFileSync(file,'utf8');
 // Only module declarations. A JSON field such as "reserve_from":"windup"
 // is data, and must never be interpreted as a package dependency.
 for(const match of original.matchAll(/^\s*import\s+(?:[^;'"]*?\s+from\s*)?['"]([^'"]+)['"]/gm)){
  if(!match[1].startsWith('.'))throw Error('Shared code must be platform independent');visit(resolve(dirname(file),match[1]));
 }
 const rel=relative(root,file),target=resolve(out,rel.replace(/\.js$/,'.ts'));
 mkdirSync(dirname(target),{recursive:true});writeFileSync(target,'// @ts-nocheck\n// GENERATED by scripts/cocos/sync-shared.mjs; edit the root JS source.\n'+original.replace(/(from\s*['"][^'"]+)\.js(['"])/g,'$1$2'));
 manifest.push({source:rel,sha256:createHash('sha256').update(original).digest('hex')});
}
// Generate only current host dependencies, preserving retained Cocos asset UUIDs.
for(const name of readdirSync(resolve(root,'cocos-pilot/assets/scripts')).filter(n=>n.endsWith('.ts'))){
 const source=readFileSync(resolve(root,'cocos-pilot/assets/scripts',name),'utf8');
 for(const match of source.matchAll(/from\s*['"]\.\/shared\/(js\/[^'"]+)['"]/g))visit(resolve(root,match[1]+'.js'));
}
const targets=new Set(manifest.map(m=>resolve(out,m.source.replace(/\.js$/,'.ts'))));
function prune(folder){
 if(!existsSync(folder))return;
 for(const entry of readdirSync(folder,{withFileTypes:true})){
  const file=resolve(folder,entry.name);
  if(entry.isDirectory()){
   prune(file);
   if(!readdirSync(file).length){rmSync(file,{recursive:true});if(existsSync(file+'.meta'))rmSync(file+'.meta');}
  }else if(entry.name.endsWith('.ts')&&!targets.has(file)){
   rmSync(file);if(existsSync(file+'.meta'))rmSync(file+'.meta');
  }
 }
}
prune(out);
writeFileSync(resolve(root,'cocos-pilot/shared-manifest.json'),JSON.stringify(manifest,null,2)+'\n');
console.log(`Synced ${seen.size} current gameplay module(s)`);
