"""Package visually reviewed real photographs and retain full attribution."""
import json,re,hashlib
from pathlib import Path
from PIL import Image,ImageOps
root=Path(__file__).resolve().parent.parent
selection=json.loads((root/'scripts/catalogue-photo-selection.json').read_text())
out=root/'assets/exploration/catalogue-photos';out.mkdir(exist_ok=True)
manifest=[];credits={}
for species,indices in selection.items():
 candidates=json.loads((Path('/tmp/rainy-photo-candidates')/species/'candidates.json').read_text())
 credits[species]=[]
 for i,index in enumerate(indices):
  p=candidates[index]
  assert p['license'] in ('cc0','cc-by')
  name=f'{species}-{i}.jpg';path=out/name
  with Image.open(p['candidatePath']) as original:
   image=ImageOps.exif_transpose(original).convert('RGB');image.thumbnail((720,720))
   image.save(path,quality=76,optimize=True)
  author=re.sub(r'^\(c\)\s*','',p['attribution']).split(', some rights')[0]
  credit='CC0' if p['license']=='cc0' else author+' · CC BY'
  credits[species].append(credit)
  manifest.append({k:v for k,v in p.items() if k!='candidatePath'}|{
   'speciesId':species,'localPath':str(path.relative_to(root)),
   'licenseUrl':'https://creativecommons.org/publicdomain/zero/1.0/' if p['license']=='cc0' else 'https://creativecommons.org/licenses/by/4.0/',
   'modifications':'EXIF orientation applied; resized to at most 720px; JPEG recompression. No compositing or generated content.',
   'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),
   'retrievedAt':'2026-09-14'})
(out/'ATTRIBUTION.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
(root/'js/data/cataloguePhotoCredits.js').write_text('// Generated by scripts/build-catalogue-photos.py; full licenses and sources accompany the photos.\nexport const CATALOGUE_PHOTO_CREDITS=Object.freeze('+json.dumps(credits,ensure_ascii=False,indent=2)+')\n')
print(f'Packaged {len(manifest)} photos, {sum(p.stat().st_size for p in out.glob("*.jpg"))} bytes')
